/** Добавить комментарий к звонку */
export interface AddCallCommentRequest {
  /** ID звонка */
  callId: number;
  /**
   * Текст комментария — попадает в поле «Описание»
   *
   * Поле текстовое, без разметки: перенос строки работает любым способом —
   * `\n`, `\r` или `\r\n`
   */
  text: string;
}

/** Добавить транскрибацию к звонку */
export interface AddCallTranscriptionRequest {
  /** ID звонка */
  callId: number;
  /**
   * Текст транскрибации
   *
   * Поле отображается в школе как HTML: абзац — `<p>текст</p>`, простой перенос
   * строки — `<br>`. Голый `\n` сохранится и вернётся в ответе `getDealCalls`,
   * но при отображении схлопнется в пробел. Символы `<`, `>` и `&` из
   * расшифровки нужно экранировать — иначе они попадут в разметку как теги
   *
   * У поля есть предел, который GetCourse не документирует: на превышении API
   * отвечает 500 с пустым errors. Замеры по живому API: кириллица — около 4600
   * символов, латиница — больше 60 000, текст пополам — около 8700. Безопасный
   * ориентир для русского текста — до 4000 символов
   */
  text: string;
}
